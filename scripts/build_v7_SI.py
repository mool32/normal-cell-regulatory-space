# ===== Fig S3: QC-trap (22-candidate screen) =====
qc=pd.read_csv(ROOT+'/results/paper3_v6_4_extras/QC_ngenes_22cancers.csv').sort_values('median')
excl=qc[qc['median']<1000]['cancer'].tolist(); repl={'AML','MM'}
fig,(a1,a2)=plt.subplots(1,2,figsize=F.panel_size(1.0, 3.1),gridspec_kw={'width_ratios':[2.3,1]})
cols=['#c0392b' if c<1000 else '#27ae60' for c in qc['median']]
a1.bar(range(len(qc)),qc['median'],color=cols,edgecolor='k',lw=.4)
a1.axhline(1000,ls='--',color='k',lw=1); a1.text(len(qc)-0.5,1060,'QC floor = 1000 genes/cell',fontsize=BASE*0.86,ha='right')
a1.set_xticks(range(len(qc))); a1.set_xticklabels(qc['cancer'],rotation=55,ha='right',fontsize=BASE*0.905)
a1.set_ylabel('median detected\ngenes per cell',fontsize=BASE*0.95)  # one line was taller than the axes and ran off the canvas
a1.set_ylim(0, qc['median'].max()*1.26)   # headroom for the rotated annotations below
a1.set_title('A',fontsize=BASE*0.98,loc='left',weight='bold')
for i,(c,m) in enumerate(zip(qc['cancer'],qc['median'])):
    if c in excl: a1.annotate('replaced (GEO)' if c in repl else 'dropped',(i,m),fontsize=BASE*0.825,rotation=90,va='bottom',ha='center',color='#c0392b',xytext=(i,m+30))
# per-target complexity (duet vs artifact)
tc=pd.read_csv(ROOT+'/results/paper3_v6_4_extras/target_complexity.csv').set_index('cell')
keyc=['erythrocytes','late spermatids','pancreatic acinar cells','megakaryocytes','esophageal apical cells','gastric progenitor cells','cytotrophoblasts']
vals=tc.loc[keyc,'median_ngenes']; bcol=['#888' if c in EXCL or 'spermatid' in c else '#c0392b' if c in ['megakaryocytes','cytotrophoblasts'] else '#e69138' for c in keyc]
a2.barh(range(len(keyc)),vals,color=bcol,edgecolor='k',lw=.4); a2.axvline(1000,ls='--',color='k',lw=1)
a2.set_yticks(range(len(keyc))); a2.set_yticklabels([c.replace(' cells','') for c in keyc],fontsize=BASE*0.943); a2.invert_yaxis()
a2.set_xlabel('median genes per assigned cell',fontsize=BASE*0.86)
a2.set_title('B',fontsize=BASE*0.98,loc='left',weight='bold')
plt.tight_layout(); plt.savefig(FIG+'/v7_figS3_qctrap.png',dpi=200,bbox_inches='tight',pad_inches=0.18); plt.close(); print('FigS3 done')

# ===== Fig S4: pre-QC recurrence, INCLUDING the quarantined cells =====
# This panel used to recompute the ranking from panel_25_top1_matrix.csv. Since E41_regen_ranking.py
# drops the quarantined cells from that matrix, the "pre-QC" figure silently rendered the POST-QC
# ranking: the erythrocyte vanished altogether and the "low-complexity artifact" arrow pointed at the
# gastric progenitor instead. The true pre-quarantine ranking is regenerated by E45 and read here.
pq=pd.read_csv(OUT+'/E45_preQC_ranking.csv').head(12).reset_index(drop=True)
QUAR={'erythrocytes','platelets','reticulocytes'}
fig,ax=plt.subplots(figsize=F.panel_size(1.0, 1.64))
cc=['#7f8c8d' if c in QUAR else '#c0392b' if c in ('megakaryocytes','cytotrophoblasts') else '#e69138'
    for c in pq.cell]
bars=ax.bar(range(len(pq)),pq.recurrence_top5,color=cc,edgecolor='k',lw=.5)
for i,c in enumerate(pq.cell):
    if c in QUAR: bars[i].set_hatch('////')
ax.set_xticks(range(len(pq)))
ax.set_xticklabels([c.replace(' cells','').replace(' ','\n',1) for c in pq.cell],
                   rotation=40,ha='right',fontsize=BASE*0.825)
ax.set_ylabel('recurrence (# of 25 cancers, top-5)',fontsize=BASE*0.92)
_e=pq.index[pq.cell=='erythrocytes']
if len(_e):
    k=int(_e[0]); v=int(pq.recurrence_top5.iloc[k])
    ax.annotate('quarantined\nlow-complexity artifact',(k,v),xytext=(k+1.8,v+2.4),
                fontsize=BASE*0.80,color='#7f8c8d',ha='left',
                arrowprops=dict(arrowstyle='->',color='#7f8c8d'))
    ax.set_ylim(0,max(pq.recurrence_top5)*1.30)
for sp in ('top','right'): ax.spines[sp].set_visible(False)
ax.grid(axis='y',alpha=.22,zorder=0)
plt.savefig(FIG+'/v7_figS4_preQC_erythrocyte.png',dpi=200,bbox_inches='tight'); plt.close(); print('FigS4 done (pre-QC, erythrocyte included)')

